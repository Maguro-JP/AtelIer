"""精度優先の「確かめる工程」の項目。工程ごとに確かめる項目と、検品が返した崩れの文をどの項目に振り分けるかを決める。

崩れの文は検品ごとに形が違う（「手 1: 指が 6 本」「重心が足の上に無い（0.7）」など）。項目ごとに確かめ・直し・確かめ直しを
分けるため、文の中の語で 1 つの項目に振り分ける。語の並びは、広い語より狭い語を先にする
（「反転すると顔が…」を顔ではなく反転に、「重心が足の上に無い」を足ではなく重心に、「目の光が無い」を顔ではなく目の光に入れる）。
どの項目の語にも当たらない崩れは「ほかの崩れ」に入れ、黙って捨てない（検品から崩れを逃がさない）。
"""
from __future__ import annotations

UNREADABLE = "検品できませんでした"   # 読めない絵は崩れとして扱う（「崩れが無い」にしない）
OTHER = "ほかの崩れ"
READABLE = "読めるか"

# (項目, 当たる語)。上から順に見て、最初に当たった項目に入れる
KEYWORDS = [
    (READABLE, ("検品できません",)),
    ("反転して見る", ("反転",)),
    ("縮めて見る", ("縮める",)),
    ("人数", ("人数",)),
    ("頼んだ物", ("描かれていない", "頼んでいない", "追加指示")),
    ("頼み", ("頼み",)),
    ("画面の重さ", ("重さ",)),
    ("重心と等身", ("重心", "等身")),
    ("骨組みの比", ("骨", "腕", "脚", "頭")),
    ("目の光", ("目の光",)),
    ("手", ("手", "指")),
    ("足", ("足",)),
    ("顔", ("顔", "目")),
    ("線の途切れ", ("輪郭", "線")),
    ("光の向き", ("光の向き",)),
    ("影", ("影",)),
    ("色の差", ("色",)),
]

# 工程ごとに、計画に初めから並べる確かめる項目（phases.PHASES と同じ順）。崩れが出た項目がこの表に無ければ、その工程の確かめの最後に足す
PHASE_ITEMS = [
    ["頼み"],                                       # 目的
    ["人数", "頼んだ物", "画面の重さ"],              # サムネイル
    ["人数", "重心と等身", "骨組みの比", "手", "足", "顔", "頼んだ物"],   # アタリ（構図の調整と下描き）
    ["線の途切れ"],                                  # 線画
    ["色の差"],                                      # 下塗り
    ["光の向き"],                                    # 光源
    ["影"],                                          # 影 2 段
    ["目の光"],                                      # 光・艶・目のハイライト
    ["手", "足", "顔", "骨組みの比", "縮めて見る", "反転して見る"],   # 仕上げ
]

# 検品の枠（手・足・顔の箱）で囲んで直す項目
REGION_ITEMS = ("手", "足", "顔")


def item_of(flaw: str) -> str:
    text = str(flaw)
    for item, words in KEYWORDS:
        if any(w in text for w in words):
            return item
    return OTHER


def split(flaws) -> dict[str, list[str]]:
    """崩れの文を項目ごとに分ける（項目の順は崩れの出た順）"""
    out: dict[str, list[str]] = {}
    for f in flaws:
        out.setdefault(item_of(f), []).append(str(f))
    return out
