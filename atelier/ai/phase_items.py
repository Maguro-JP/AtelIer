# 「左右対称」は「タイヤの丸み」より先に見る（「左右のタイヤの大きさが違う」は「タイヤ」を含むので、対称より先に見ないとタイヤの丸みになってしまう）
# 「遠近の収束」は「線の途切れ」より先に見る（「遠近の収束が無い（線の角度の差 …）」は「線」を含むので、収束より先に見ないと線の途切れになってしまう）
